"""Benchmark for src/jax_ik's InverseKinematicsSolver.

Similar in spirit to ik_jax.py (arm-reach IK with a few "look at" style
regularizers), but built against the current jax_ik library and exercising
several more of its objectives: a mandatory position target plus optional
look-at, smoothness (velocity/accel/jerk) and init-pose regularizers.

Targets are generated by FK-sampling random poses within the joint bounds,
so every target is guaranteed reachable (the solver's job is finding a good
pose, not chasing an out-of-workspace point). Targets are cached to a JSON
file next to this script so repeated runs (across different commits/
experiments) always solve for the exact same 500 points -- a fair,
apples-to-apples comparison.

Usage: `python ik_jax_lib_bench.py` (run from the paper_evaluation/
directory, or anywhere -- paths below are resolved relative to this file).
Prints a single machine-parseable summary line:
    RESULT time_ms=<avg per-solve ms> success_rate=<pct> memory_mb=<peak MB>
"""

import json
import os
import resource
import sys
import time

import numpy as np

_HERE = os.path.dirname(os.path.abspath(__file__))
_ROOT = os.path.dirname(_HERE)
sys.path.insert(0, os.path.join(_ROOT, "src"))

from jax_ik.ik import InverseKinematicsSolver  # noqa: E402
from jax_ik.objectives import (  # noqa: E402
    BoneRelativeLookObj,
    CombinedDerivativeObj,
    DistanceObjTraj,
    InitPoseObj,
)
from jax_ik.smplx_statics import left_arm_bounds_dict  # noqa: E402

# ---------------------------------------------------------------------------
# Frozen benchmark configuration. Do not change these when iterating on
# src/jax_ik/ -- they define the baseline. Only the solver internals should
# change between experiments.
# ---------------------------------------------------------------------------
MODEL_FILE = os.path.join(_ROOT, "smplx.glb")
CONTROLLED_BONES = ["left_collar", "left_shoulder", "left_elbow", "left_wrist"]
EE_BONE = "left_wrist"

NUM_TARGETS = 500
SEED = 12345
THRESHOLD = 0.005
NUM_STEPS = 500
LEARNING_RATE = 0.2
PATIENCE = 200

LOOK_WEIGHT = 0.0035
DERIV_WEIGHT = 1.5e-5
INIT_POSE_WEIGHT = 1e-6

TARGETS_CACHE = os.path.join(_HERE, "bench_targets_500.json")


def _build_bounds():
    bounds = []
    for bone in CONTROLLED_BONES:
        lower, upper = left_arm_bounds_dict[bone]
        for l, u in zip(lower, upper):
            bounds.append((l, u))
    return bounds


def _build_solver():
    return InverseKinematicsSolver(
        model_file=MODEL_FILE,
        controlled_bones=CONTROLLED_BONES,
        bounds=_build_bounds(),
        threshold=THRESHOLD,
        num_steps=NUM_STEPS,
        compute_sdf=False,
    )


def _generate_targets(solver, n, seed):
    """FK-sample n guaranteed-reachable end-effector positions."""
    rng = np.random.default_rng(seed)
    lo = np.asarray(solver.lower_bounds)
    hi = np.asarray(solver.upper_bounds)
    targets = []
    for _ in range(n):
        angles = rng.uniform(lo, hi).astype(np.float32)
        fk = solver.fk_solver.compute_fk_from_angles(angles)
        _, tail = solver.fk_solver.get_bone_head_tail_from_fk(fk, EE_BONE)
        targets.append(np.asarray(tail, dtype=np.float32).tolist())
    return targets


def _load_or_generate_targets(solver):
    if os.path.exists(TARGETS_CACHE):
        with open(TARGETS_CACHE, "r") as f:
            data = json.load(f)
        if data.get("seed") == SEED and len(data.get("targets", [])) == NUM_TARGETS:
            return [np.asarray(t, dtype=np.float32) for t in data["targets"]]
    targets = _generate_targets(solver, NUM_TARGETS, SEED)
    with open(TARGETS_CACHE, "w") as f:
        json.dump({"seed": SEED, "targets": targets}, f)
    return [np.asarray(t, dtype=np.float32) for t in targets]


def _build_objectives(solver, target):
    zeros = np.zeros(len(CONTROLLED_BONES) * 3, dtype=np.float32)

    mandatory = (
        DistanceObjTraj(
            bone_name=EE_BONE,
            target_points=target,
            use_head=False,
            weight=1.0,
        ),
    )
    optional = (
        BoneRelativeLookObj(
            bone_name=EE_BONE,
            use_head=False,
            modifications=[(1, 1.0)],
            weight=LOOK_WEIGHT,
        ),
        BoneRelativeLookObj(
            bone_name=EE_BONE,
            use_head=False,
            modifications=[(2, 1.0)],
            weight=LOOK_WEIGHT,
        ),
        BoneRelativeLookObj(
            bone_name="left_shoulder",
            use_head=False,
            modifications=[(2, -1.0)],
            weight=LOOK_WEIGHT,
        ),
        CombinedDerivativeObj(max_order=3, weight=DERIV_WEIGHT),
        InitPoseObj(
            init_rot=zeros,
            full_trajectory=False,
            last_position=True,
            weight=INIT_POSE_WEIGHT,
        ),
    )
    return mandatory, optional


def run_benchmark(verbose=True):
    solver = _build_solver()
    targets = _load_or_generate_targets(solver)

    # Warm up JIT compilation; not counted in timing.
    mand, opt = _build_objectives(solver, targets[0])
    for _ in range(2):
        solver.solve(
            initial_rotations=None,
            learning_rate=LEARNING_RATE,
            mandatory_objective_functions=mand,
            optional_objective_functions=opt,
            ik_points=1,
            patience=PATIENCE,
            verbose=False,
        )

    successes = 0
    total_elapsed = 0.0
    for i, target in enumerate(targets):
        mand, opt = _build_objectives(solver, target)
        start = time.perf_counter()
        _, best_obj, _ = solver.solve(
            initial_rotations=None,
            learning_rate=LEARNING_RATE,
            mandatory_objective_functions=mand,
            optional_objective_functions=opt,
            ik_points=1,
            patience=PATIENCE,
            verbose=False,
        )
        elapsed = time.perf_counter() - start
        total_elapsed += elapsed
        if best_obj < THRESHOLD:
            successes += 1
        if verbose and (i + 1) % 100 == 0:
            print(
                f"[{i + 1}/{len(targets)}] running success rate: "
                f"{successes / (i + 1) * 100:.2f}%",
                file=sys.stderr,
            )

    avg_time_ms = total_elapsed / len(targets) * 1000.0
    success_rate = successes / len(targets) * 100.0
    peak_rss_kb = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    peak_memory_mb = peak_rss_kb / 1024.0

    return avg_time_ms, success_rate, peak_memory_mb


def main():
    avg_time_ms, success_rate, peak_memory_mb = run_benchmark(verbose=True)
    print(
        f"RESULT time_ms={avg_time_ms:.6f} success_rate={success_rate:.2f} "
        f"memory_mb={peak_memory_mb:.1f}"
    )


if __name__ == "__main__":
    main()
